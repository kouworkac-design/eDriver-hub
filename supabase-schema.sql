
-- 動画テーブル
create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  youtube_id text not null,
  title text not null,
  description text default '',
  category text not null check (
    category in (
      'KYT',
      'フォークリフト',
      'テールゲートリフト',
      '安全講習'
    )
  ),
  created_at timestamptz not null default now()
);

-- 管理者テーブル
create table if not exists public.video_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- RLSを有効化
alter table public.videos enable row level security;
alter table public.video_admins enable row level security;

-- 管理者判定関数
create or replace function public.is_video_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.video_admins
    where user_id = (select auth.uid())
  );
$$;

-- 動画は誰でも閲覧可能
drop policy if exists "Videos are viewable by everyone"
on public.videos;

create policy "Videos are viewable by everyone"
on public.videos
for select
to anon, authenticated
using (true);

-- 管理者のみ動画追加可能
drop policy if exists "Admins can insert videos"
on public.videos;

create policy "Admins can insert videos"
on public.videos
for insert
to authenticated
with check ((select public.is_video_admin()));

-- 管理者のみ動画編集可能
drop policy if exists "Admins can update videos"
on public.videos;

create policy "Admins can update videos"
on public.videos
for update
to authenticated
using ((select public.is_video_admin()))
with check ((select public.is_video_admin()));

-- 管理者のみ動画削除可能
drop policy if exists "Admins can delete videos"
on public.videos;

create policy "Admins can delete videos"
on public.videos
for delete
to authenticated
using ((select public.is_video_admin()));

-- 管理者は自分自身の管理者登録情報だけ確認可能
drop policy if exists "Admins can view own admin record"
on public.video_admins;

create policy "Admins can view own admin record"
on public.video_admins
for select
to authenticated
using (user_id = (select auth.uid()));

-- 管理者テーブルへのブラウザからの追加・変更・削除は許可しない

-- Realtimeへの登録
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'videos'
  ) then
    alter publication supabase_realtime add table public.videos;
  end if;
end
$$;

-- --------------------------------------------------
-- SCORM体験版：ユーザーごとの閲覧許可（2026-11-28 追加・適用済み）
-- --------------------------------------------------
alter table public.named_users
  add column if not exists scorm_demo_enabled boolean not null default false;

create or replace function public.can_view_scorm_demo()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_video_admin() or exists (
    select 1 from public.named_users
    where user_id = (select auth.uid())
      and is_active
      and scorm_demo_enabled
  );
$$;
revoke all on function public.can_view_scorm_demo() from public, anon;
grant execute on function public.can_view_scorm_demo() to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('scorm-demo', 'scorm-demo', false, 52428800, array['text/html', 'video/mp4'])
on conflict (id) do nothing;

create policy "SCORM demo: permitted users can read"
  on storage.objects for select to authenticated
  using (bucket_id = 'scorm-demo' and (select public.can_view_scorm_demo()));
create policy "SCORM demo: admins can upload"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'scorm-demo' and (select public.is_video_admin()));
create policy "SCORM demo: admins can update"
  on storage.objects for update to authenticated
  using (bucket_id = 'scorm-demo' and (select public.is_video_admin()))
  with check (bucket_id = 'scorm-demo' and (select public.is_video_admin()));
create policy "SCORM demo: admins can delete"
  on storage.objects for delete to authenticated
  using (bucket_id = 'scorm-demo' and (select public.is_video_admin()));
